# Function to Calculate Area
def calculate_area(length, width):
    area = length * width
    return area

# Calling Function with Different Values
area1 = calculate_area(5, 4)
area2 = calculate_area(10, 8)
area3 = calculate_area(7, 3)

print("Area of Rectangle 1:", area1)
print("Area of Rectangle 2:", area2)
print("Area of Rectangle 3:", area3)