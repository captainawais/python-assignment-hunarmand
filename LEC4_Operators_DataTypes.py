# Integer Operations
a = 20
b = 6

print("INTEGER OPERATIONS")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)

print()

# Float Operations
x = 10.5
y = 2.5

print("FLOAT OPERATIONS")
print("Addition:", x + y)
print("Subtraction:", x - y)
print("Multiplication:", x * y)
print("Division:", x / y)
print("Modulus:", x % y)

print()

# String Operations
first_name = "Awais"
last_name = "Farooq"

# Concatenation
full_name = first_name + " " + last_name

# Repetition
repeat_name = first_name * 3

